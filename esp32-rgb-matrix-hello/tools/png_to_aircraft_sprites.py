#!/usr/bin/env python3
"""Turn the editable 33x33 aircraft PNG library into the firmware header.

White pixels are lit LEDs and black pixels are off. The PNGs are deliberately
one-bit and must remain exactly 33x33; alpha, scaling, and anti-aliasing are
not part of the format.
"""

import argparse
from pathlib import Path

from PIL import Image

SIZE = 33
CATEGORIES = [
    "widebody_four_engine", "widebody_twin_jet", "narrowbody_jet",
    "regional_jet", "turboprop", "light_prop", "business_jet",
    "helicopter", "generic_747", "fighter_jet", "superheavy",
]


def read_mask(path: Path):
    image = Image.open(path).convert("1")
    if image.size != (SIZE, SIZE):
        raise ValueError(f"{path.name} must be exactly {SIZE}x{SIZE}, got {image.width}x{image.height}")
    pixels = image.load()
    return [sum(1 << (32 - x) for x in range(SIZE) if pixels[x, y]) for y in range(SIZE)]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("sprite_directory", type=Path, help="Directory containing the nine named 33x33 PNGs")
    parser.add_argument("output", type=Path, help="Generated include/aircraft_sprites.h path")
    args = parser.parse_args()

    masks = []
    for category in CATEGORIES:
        path = args.sprite_directory / f"{category}.png"
        if not path.exists():
            raise FileNotFoundError(f"Missing required sprite: {path}")
        masks.append(read_mask(path))

    lines = [
        "// Generated by tools/png_to_aircraft_sprites.py; do not edit by hand.",
        "// Edit assets/aircraft-sprites/*.png, then regenerate this file.",
        "#pragma once",
        "",
        f"constexpr uint8_t kAircraftSpriteCount = {len(CATEGORIES)};",
        "constexpr uint8_t kAircraftSpriteSize = 33;",
        "constexpr uint64_t kAircraftSpriteMasks[kAircraftSpriteCount][kAircraftSpriteSize] PROGMEM = {",
    ]
    for category, rows in zip(CATEGORIES, masks):
        lines.append(f"  // {category}")
        lines.append("  {")
        for index in range(0, SIZE, 3):
            lines.append("    " + ", ".join(f"0x{row:09X}ULL" for row in rows[index:index + 3]) + ",")
        lines.append("  },")
    lines.extend(["};", ""])
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
